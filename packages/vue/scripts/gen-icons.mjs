/**
 * Generates `src/icons/nodes.ts` from lucide-react's ESM icon modules.
 *
 * The Vue package deliberately does not depend on an icon runtime: the icons
 * are a handful of static paths, and shipping the exact node data keeps the
 * rendered SVG identical to what lucide-react produces (same attributes, same
 * `lucide lucide-<name>` class), which is what the class-parity smoke checks.
 *
 *   node scripts/gen-icons.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

// Keep in sync with library/components/*.tsx imports.
const ICONS = {
  "alert-circle": "AlertCircle",
  "alert-triangle": "AlertTriangle",
  "check-circle-2": "CheckCircle2",
  info: "Info",
  "chevron-right": "ChevronRight",
  "chevron-down": "ChevronDown",
  check: "Check",
  x: "X",
  "loader-circle": "LoaderCircle",
  search: "Search",
  eye: "Eye",
  "eye-off": "EyeOff",
  clock: "Clock",
  "octagon-x": "OctagonX",
};

function iconNodePath(slug) {
  return resolve(here, "../../../node_modules/lucide-react/dist/esm/icons", `${slug}.js`);
}

/** Some slugs are aliases (`export { default } from './circle-alert.js'`). */
function readIconSource(slug, hops = 0) {
  if (hops > 3) throw new Error(`Icon alias chain too deep: ${slug}`);
  const source = readFileSync(iconNodePath(slug), "utf8");
  const alias = source.match(/export \{ default \} from '\.\/([\w-]+)\.js';/);
  return alias ? readIconSource(alias[1], hops + 1) : { source, canonical: slug };
}

function extract(slug, componentName) {
  const { source, canonical } = readIconSource(slug);
  const match = source.match(/const __iconNode = (\[[\s\S]*?\]);/);
  if (!match) throw new Error(`Could not read __iconNode from ${slug}.js (${componentName})`);
  // The literal is a JS array of [tag, {attrs}] pairs with bare identifiers
  // and CSS-ish keys, so evaluate it rather than JSON.parse. Local dependency.
  const node = new Function(`return ${match[1]}`)();
  // lucide-react derives the CSS class from the CANONICAL slug, not the
  // component name: `AlertTriangle` from triangle-alert.js is
  // `lucide lucide-triangle-alert`. Keep that so markup stays identical.
  return {
    canonical,
    children: node.map(([tag, attrs]) => {
      const { key: _key, ...rest } = attrs;
      return [tag, rest];
    }),
  };
}

const entries = Object.entries(ICONS).map(([slug, name]) => {
  const { canonical, children } = extract(slug, name);
  return `  ${JSON.stringify(slug)}: { canonical: ${JSON.stringify(canonical)}, children: ${JSON.stringify(children)} },`;
});

const out = `// GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// Source: lucide-react ${JSON.parse(readFileSync(resolve(here, "../../../node_modules/lucide-react/package.json"), "utf8")).version} (ISC)
export type IconChild = [string, Record<string, string>];

export interface IconDefinition {
  /** lucide's canonical slug — the class name suffix lucide-react emits. */
  canonical: string;
  children: IconChild[];
}

export const ICON_NODES: Record<string, IconDefinition> = {
${entries.join("\n")}
};
`;

mkdirSync(resolve(here, "../src/icons"), { recursive: true });
writeFileSync(resolve(here, "../src/icons/nodes.ts"), out);
console.log(`wrote src/icons/nodes.ts (${Object.keys(ICONS).length} icons)`);
